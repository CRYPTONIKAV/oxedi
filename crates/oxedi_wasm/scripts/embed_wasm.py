"""Embed the viewer's WebAssembly module and its sample file in ES modules.

The page's Content-Security-Policy forbids every connection (`connect-src
'none'`), so nothing can be fetched after the page loads: the module bytes and
the sample travel inside JavaScript files the page imports, as base64 string
literals decoded into `Uint8Array`s.

Reads `viewer/pkg/oxedi_bg.wasm` (written by wasm-bindgen) and the sample
fixture; writes into `viewer/pkg`:

- `module.js`: exports `WASM`, the module's bytes;
- `sample.js`: exports `SAMPLE`, the sample's bytes, and `SAMPLE_NAME`;
- `index.js`: instantiates the module synchronously from `WASM` and
  re-exports `parse` and `version`.

Standard library only. Run from anywhere: paths are resolved from this file.
"""

from __future__ import annotations

import base64
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
PKG = ROOT / "viewer" / "pkg"
WASM = PKG / "oxedi_bg.wasm"
GLUE = PKG / "oxedi.js"
SAMPLE = ROOT / "crates" / "oxedi_core" / "tests" / "fixtures" / "balanced_5010_sample.txt"
SAMPLE_NAME = "balanced_5010_sample.835"

INDEX = """\
// Generated by crates/oxedi_wasm/scripts/embed_wasm.py; do not edit.
import { initSync, parse, version } from "./oxedi.js";
import { WASM } from "./module.js";

initSync({ module: WASM });

export { parse, version };
"""


def bytes_module(name: str, data: bytes, extra: str = "") -> str:
    """An ES module exporting `data` as the `Uint8Array` named `name`."""
    encoded = base64.b64encode(data).decode("ascii")
    return (
        "// Generated by crates/oxedi_wasm/scripts/embed_wasm.py; do not edit.\n"
        f'const text = atob("{encoded}");\n'
        f"export const {name} = Uint8Array.from(text, (c) => c.charCodeAt(0));\n"
        f"{extra}"
    )


def init_sync_problem(glue: str) -> str | None:
    """Why the glue's `initSync` cannot run under the page's policy, or `None`.

    The body of `initSync` runs from its declaration to the next top-level
    `function`; it must not call `fetch`.
    """
    start = glue.find("\nfunction initSync(")
    if start < 0:
        return "no top-level `function initSync(` (the wasm-bindgen glue changed shape)"
    end = glue.find("\nfunction ", start + 1)
    async_end = glue.find("\nasync function ", start + 1)
    ends = [at for at in (end, async_end) if at >= 0]
    body = glue[start : min(ends) if ends else len(glue)]
    if "fetch(" in body:
        return "initSync calls fetch, which the page's connect-src 'none' forbids"
    return None


def main() -> int:
    for path in (WASM, GLUE, SAMPLE):
        if not path.is_file():
            print(f"embed_wasm: {path.relative_to(ROOT)} is missing; run make wasm", file=sys.stderr)
            return 1
    problem = init_sync_problem(GLUE.read_text(encoding="utf-8"))
    if problem:
        print(f"embed_wasm: {GLUE.relative_to(ROOT)}: {problem}", file=sys.stderr)
        return 1
    (PKG / "module.js").write_text(bytes_module("WASM", WASM.read_bytes()), encoding="utf-8")
    (PKG / "sample.js").write_text(
        bytes_module(
            "SAMPLE",
            SAMPLE.read_bytes(),
            f"export const SAMPLE_NAME = {json.dumps(SAMPLE_NAME)};\n",
        ),
        encoding="utf-8",
    )
    (PKG / "index.js").write_text(INDEX, encoding="utf-8")
    print(f"embed_wasm: wrote module.js, sample.js and index.js into {PKG.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
